function substringAfterLast(s) {
    const idx = s.lastIndexOf("|"); // find the *last* occurrence of "|"
    if (idx === -1) {
        return idx;
    }
    return s.substring(idx + 1);
}

geofs.api.map.updateMarkerLayers = function() {
        var e = this._map.getZoom();
        for (var t in geofs.api.map.markerLayers) {
            var a = geofs.api.map.markerLayers[t];
            if (e > a.minZoom && e < a.maxZoom) {
                var o = this.getVisibleTiles(this._map.getBounds(), a.tileSize);
                for (var n in a.visibileTiles)
                    o[n] || this.hideTile(a, n);
                for (var n in o)
                    this.showTile(a, n)
            } else if (e > a.maxZoom) {
                var o = this.getVisibleTiles(this._map.getBounds(), a.tileSize);
                for (var n in a.visibileTiles)
                    o[n] || this.hideTile(a, n);
                for (var n in o)
                    if (a.visibileTiles) {}
                    this.showTile(a, n)
            } else
                for (var n in a.visibileTiles)
                    this.hideTile(a, n)
        }
    }

geofs.map.addRunwayMarker = function(e) {
    var t = {
        coords: [e.lat, e.lon],
        radius: geofs.map.runwayMarkerRadius-3,
        color: "#ffffff",
        zIndex: 1e3,
        fillColor: e.major ? "#184888" : "#ffd200",
        popup: geofs.map.runwayMarkerPopup,
        pane: "overlayPane",
        popupMinWidth: 200,
        closeButton: !1,
        keepToFront: !0,
        runway: e
    };
    if (airbaseIcaos.includes(substringAfterLast(e.name))) {
        if (e.major) {
            t.fillColor = airbaseColor
            t.radius = geofs.map.runwayMarkerRadius
        }
        geofs.api.map.addLayeredMarker(e.major ? "major" : "minor", t)
    }
}

